export function budgetTrace(pattern: string, params: TraceParams): string {
  return pattern.replace(
    '{amount}',
    new Intl.NumberFormat(undefined, {
      style: 'currency',
      currency: 'USD',
      maximumFractionDigits: 6,
    }).format(params.amount ?? 0),
  );
}
